const normalize = (text: string) =>
  text.toLowerCase().replace(/ё/g, "е").replace(/[!?.,:;()"]/g, " ").replace(/\s+/g, " ").trim();

export function answerFromKeywords(question: string): string {
  const q = normalize(question);
  const best = keywordEntries
    .map((e) => ({ e, score: e.keywords.filter((k) => q.includes(normalize(k))).length }))
    .sort((a, b) => b.score - a.score)[0];
  return best && best.score > 0
    ? best.e.content
    : "Сейчас не могу ответить подробно. Оставь заявку или позови Айнура — он ответит лично.";
}
